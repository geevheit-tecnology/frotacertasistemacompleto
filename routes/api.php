<?php

use App\Http\Controllers\Api\AuthController;
use App\Http\Controllers\Api\AlertController;
use App\Http\Controllers\Api\AuditLogController;
use App\Http\Controllers\Api\BranchController;
use App\Http\Controllers\Api\ChecklistExecutionController;
use App\Http\Controllers\Api\ChecklistTemplateController;
use App\Http\Controllers\Api\CompanyController;
use App\Http\Controllers\Api\CostCenterController;
use App\Http\Controllers\Api\DriverController;
use App\Http\Controllers\Api\DriverDocumentController;
use App\Http\Controllers\Api\EvidenceController;
use App\Http\Controllers\Api\ExecutiveReportController;
use App\Http\Controllers\Api\FinancialTransactionController;
use App\Http\Controllers\Api\FuelRecordController;
use App\Http\Controllers\Api\HealthController;
use App\Http\Controllers\Api\InsightController;
use App\Http\Controllers\Api\InvoiceController;
use App\Http\Controllers\Api\MaintenancePlanController;
use App\Http\Controllers\Api\MissionControlController;
use App\Http\Controllers\Api\NotificationController;
use App\Http\Controllers\Api\NonConformityController;
use App\Http\Controllers\Api\OilServiceRecordController;
use App\Http\Controllers\Api\InventoryPartController;
use App\Http\Controllers\Api\RuleController;
use App\Http\Controllers\Api\RuleExecutionController;
use App\Http\Controllers\Api\SupplierController;
use App\Http\Controllers\Api\TachographRecordController;
use App\Http\Controllers\Api\TaskController;
use App\Http\Controllers\Api\TireController;
use App\Http\Controllers\Api\TireInspectionController;
use App\Http\Controllers\Api\UserController;
use App\Http\Controllers\Api\VehicleController;
use App\Http\Controllers\Api\VehicleCostReportController;
use App\Http\Controllers\Api\VehicleDocumentController;
use App\Http\Controllers\Api\WorkOrderController;
use Illuminate\Support\Facades\Route;

Route::get('/health', [HealthController::class, 'health']);
Route::get('/ready', [HealthController::class, 'ready']);

Route::post('/v1/auth/login', [AuthController::class, 'login']);

Route::prefix('v1')->group(function (): void {
    Route::middleware('auth.api')->group(function (): void {
        Route::get('auth/me', [AuthController::class, 'me']);
        Route::apiResource('companies', CompanyController::class)->except(['destroy'])->middleware('permission:administration.manage');
        Route::apiResource('branches', BranchController::class)->middleware('permission:administration.manage');
        Route::apiResource('users', UserController::class)->middleware('permission:administration.manage');
        Route::apiResource('vehicles', VehicleController::class)->middleware('permission:fleet.manage');
        Route::apiResource('drivers', DriverController::class)->middleware('permission:fleet.manage');
        Route::apiResource('vehicle-documents', VehicleDocumentController::class)->middleware('permission:documents.manage');
        Route::apiResource('driver-documents', DriverDocumentController::class)->middleware('permission:documents.manage');
        Route::apiResource('checklist-templates', ChecklistTemplateController::class)->only(['index', 'store', 'show'])->middleware('permission:checklist.manage');
        Route::apiResource('checklists', ChecklistExecutionController::class)->only(['index', 'store', 'show'])->middleware('permission:checklist.manage');
        Route::apiResource('non-conformities', NonConformityController::class)->only(['index', 'show', 'update'])->middleware('permission:checklist.manage');
        Route::apiResource('oil-services', OilServiceRecordController::class)->middleware('permission:maintenance.manage');
        Route::apiResource('maintenance-plans', MaintenancePlanController::class)->middleware('permission:maintenance.manage');
        Route::apiResource('tachographs', TachographRecordController::class)->middleware('permission:maintenance.manage');
        Route::apiResource('suppliers', SupplierController::class)->middleware('permission:maintenance.manage');
        Route::apiResource('inventory-parts', InventoryPartController::class)->middleware('permission:maintenance.manage');
        Route::apiResource('work-orders', WorkOrderController::class)->middleware('permission:maintenance.manage');
        Route::post('work-orders/{workOrder}/parts', [WorkOrderController::class, 'addPart'])->middleware('permission:maintenance.manage');
        Route::apiResource('tires', TireController::class)->only(['index', 'store', 'show'])->middleware('permission:tires.manage');
        Route::apiResource('tire-inspections', TireInspectionController::class)->only(['index', 'store'])->middleware('permission:tires.manage');
        Route::apiResource('fuel-records', FuelRecordController::class)->only(['index', 'store'])->middleware('permission:financial.manage');
        Route::apiResource('financial-transactions', FinancialTransactionController::class)->only(['index', 'store'])->middleware('permission:financial.manage');
        Route::apiResource('cost-centers', CostCenterController::class)->only(['index', 'store'])->middleware('permission:financial.manage');
        Route::apiResource('invoices', InvoiceController::class)->only(['index', 'store'])->middleware('permission:financial.manage');
        Route::get('reports/vehicles/{vehicle}/costs', [VehicleCostReportController::class, 'show'])->middleware('permission:financial.manage');
        Route::get('reports/executive', [ExecutiveReportController::class, 'show'])->middleware('permission:reports.view');
        Route::get('audit-logs', [AuditLogController::class, 'index'])->middleware('permission:audit.view');
        Route::get('audit-logs/export.csv', [AuditLogController::class, 'exportCsv'])->middleware('permission:audit.view');
        Route::apiResource('alerts', AlertController::class)->only(['index', 'show', 'update'])->middleware('permission:mission-control.view');
        Route::apiResource('insights', InsightController::class)->only(['index', 'show', 'update'])->middleware('permission:mission-control.view');
        Route::get('mission-control', [MissionControlController::class, 'show'])->middleware('permission:mission-control.view');
        Route::post('alerts/{alert}/tasks', [AlertController::class, 'createTask'])->middleware('permission:workflow.manage');
        Route::apiResource('rules', RuleController::class)->middleware('permission:workflow.manage');
        Route::post('rules/{rule}/execute', [RuleController::class, 'execute'])->middleware('permission:workflow.manage');
        Route::apiResource('rule-executions', RuleExecutionController::class)->only(['index', 'show'])->middleware('permission:workflow.manage');
        Route::apiResource('tasks', TaskController::class)->only(['index', 'show', 'update'])->middleware('permission:workflow.manage');
        Route::apiResource('notifications', NotificationController::class)->only(['index'])->middleware('permission:workflow.manage');
        Route::apiResource('evidences', EvidenceController::class)->only(['index', 'store'])->middleware('permission:workflow.manage');
    });
});
